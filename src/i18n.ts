/** Date range without dashes: "April 2022 to October 2024", "أكتوبر 2024 حتى الآن". */
export function range(start: T, end: T, lang: Lang) {
  if (end.en === 'Present') return lang === 'ar' ? `${start.ar} حتى الآن` : `${start.en} to Present`;
  return lang === 'ar' ? `${start.ar} إلى ${end.ar}` : `${start.en} to ${end.en}`;
}
